import pandas as pd
import joblib
import numpy as np

from pathlib import Path

from sklearn.base import clone
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix
)


# Project root directory
PROJECT_ROOT = Path(__file__).resolve().parents[2]

# Processed data paths
X_TRAIN_PATH = PROJECT_ROOT / "data" / "processed" / "x_train_processed.csv"
Y_TRAIN_PATH = PROJECT_ROOT / "data" / "processed" / "y_train.csv"

# Model directory
MODEL_DIR = PROJECT_ROOT / "models"

# Output directory
REPORT_DIR = PROJECT_ROOT / "outputs" / "reports"
REPORT_DIR.mkdir(parents=True, exist_ok=True)


def load_training_data():
    """Load the processed training dataset."""

    x_train = pd.read_csv(X_TRAIN_PATH)
    y_train = pd.read_csv(Y_TRAIN_PATH).squeeze()

    return x_train, y_train


def load_tuned_model():
    """Load the tuned Gradient Boosting model."""

    model_path = MODEL_DIR / "gradient_boosting_tuned.pkl"

    return joblib.load(model_path)


def generate_oof_probabilities(model, x_train, y_train):
    """
    Generate out-of-fold churn probabilities.

    Each customer's probability is generated by a model
    that was not trained on that customer.
    """

    print("\nGenerating out-of-fold probabilities...")

    skf = StratifiedKFold(
        n_splits=5,
        shuffle=True,
        random_state=42
    )

    oof_probabilities = np.zeros(len(y_train))

    for fold, (train_index, validation_index) in enumerate(
        skf.split(x_train, y_train),
        start=1
    ):

        print(f"\nProcessing Fold {fold}...")

        x_fold_train = x_train.iloc[train_index]
        y_fold_train = y_train.iloc[train_index]

        x_fold_validation = x_train.iloc[validation_index]

        # Clone the tuned model
        fold_model = clone(model)

        # Train on fold training data
        fold_model.fit(
            x_fold_train,
            y_fold_train
        )

        # Predict churn probability
        fold_probabilities = fold_model.predict_proba(
            x_fold_validation
        )[:, 1]

        # Store probabilities
        oof_probabilities[validation_index] = fold_probabilities

    print("\nOut-of-fold probability generation completed.")

    return oof_probabilities


def calculate_threshold_metrics(
    y_true,
    probabilities,
    threshold
):
    """Calculate classification metrics for a threshold."""

    y_pred = (
        probabilities >= threshold
    ).astype(int)

    accuracy = accuracy_score(
        y_true,
        y_pred
    )

    precision = precision_score(
        y_true,
        y_pred,
        zero_division=0
    )

    recall = recall_score(
        y_true,
        y_pred,
        zero_division=0
    )

    f1 = f1_score(
        y_true,
        y_pred,
        zero_division=0
    )

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        y_pred
    ).ravel()

    return {
        "Threshold": threshold,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "F1-Score": f1,
        "True Negatives": tn,
        "False Positives": fp,
        "False Negatives": fn,
        "True Positives": tp,
        "Customers Flagged": int(y_pred.sum())
    }


def evaluate_thresholds(
    y_true,
    probabilities
):
    """Evaluate multiple classification thresholds."""

    thresholds = np.arange(
        0.10,
        0.91,
        0.05
    )

    results = []

    for threshold in thresholds:

        metrics = calculate_threshold_metrics(
            y_true,
            probabilities,
            threshold
        )

        results.append(metrics)

    return pd.DataFrame(results)


def find_best_threshold(results_df):
    """Find the threshold with the highest F1-score."""

    best_row = results_df.loc[
        results_df["F1-Score"].idxmax()
    ]

    return best_row


def main():

    print("\nCustomer Churn - Threshold Tuning")

    # Load training data
    x_train, y_train = load_training_data()

    print("\nTraining data loaded successfully.")

    print(
        f"x_train shape: {x_train.shape}"
    )

    print(
        f"y_train shape: {y_train.shape}"
    )

    # Load tuned Gradient Boosting model
    print(
        "\nLoading tuned Gradient Boosting model..."
    )

    model = load_tuned_model()

    print(
        "Tuned Gradient Boosting model loaded successfully."
    )

    # Generate out-of-fold probabilities
    probabilities = generate_oof_probabilities(
        model,
        x_train,
        y_train
    )

    # Evaluate thresholds
    print("\nEvaluating classification thresholds...")

    results_df = evaluate_thresholds(
        y_train,
        probabilities
    )

    # Display results
    print("\nThreshold Analysis")

    print(
        results_df.to_string(
            index=False,
            float_format=lambda x: f"{x:.4f}"
        )
    )

    # Find best threshold
    best_threshold = find_best_threshold(
        results_df
    )

    print("\nBest Threshold Based on F1-Score")

    print(
        f"Threshold : "
        f"{best_threshold['Threshold']:.2f}"
    )

    print(
        f"Accuracy  : "
        f"{best_threshold['Accuracy']:.4f}"
    )

    print(
        f"Precision : "
        f"{best_threshold['Precision']:.4f}"
    )

    print(
        f"Recall    : "
        f"{best_threshold['Recall']:.4f}"
    )

    print(
        f"F1-Score  : "
        f"{best_threshold['F1-Score']:.4f}"
    )

    print(
        f"Customers Flagged: "
        f"{best_threshold['Customers Flagged']}"
    )

    # Save threshold analysis
    results_path = (
        REPORT_DIR /
        "threshold_analysis.csv"
    )

    results_df.to_csv(
        results_path,
        index=False
    )

    print(
        f"\nThreshold analysis saved to: "
        f"{results_path}"
    )


if __name__ == "__main__":
    main()